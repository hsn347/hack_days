# أقرب مستوى إذا كان المستوى أعلى من 30
MAX_KNOWN_DEPOT_LV = 30


def get_depot_capacity(depot_lv: int, resid: int) -> int:
    """
    استخراج سعة المستودع لمورد معين مع احتساب بفات حماية المخزن القياسية
    (تقريباً +62% عند المستوى 30 لتطابق سعة 1.2M الظاهرة باللعبة).
    """
    if depot_lv <= 0:
        return 0

    lookup_lv = min(depot_lv, MAX_KNOWN_DEPOT_LV)
    base = DEPOT_BASE_CAPS.get(lookup_lv, {}).get(resid, 0)
    if not base:
        # استقراء تقديري للمستويات الأعلى
        base = DEPOT_BASE_CAPS[MAX_KNOWN_DEPOT_LV].get(resid, 0)

    # مضاعف البفات (علوم وأبحاث وتطوير الحماية) يتدرج حتى ~1.62 عند مستوى 30
    buff_multiplier = 1.0 + min(0.65, (lookup_lv / 30.0) * 0.6217)
    return int(base * buff_multiplier)


def calculate_unprotected_resources(
    reslist: Dict[str, Any],
    saferes: Dict[str, Any],
    blist: Optional[List[Dict[str, Any]]] = None,
) -> Dict[str, Any]:
    """
    حساب الموارد غير المحفوظة بدقة بحسب معادلة اللعبة:
      غير المحفوظ = max(0, إجمالي الموارد - الموارد الآمنة - سعة المستودع)

    المخرجات:
      - total: الموارد الإجمالية
      - safe: الموارد الآمنة
      - depot: سعة حماية المستودع
      - unprotected: الموارد غير المحفوظة
    """
    # البحث عن مستوى المستودع (bid=105)
    depot_lv = 0
    if blist and isinstance(blist, list):
        for b in blist:
            if isinstance(b, dict) and int(b.get("bid", 0)) == 105:
                depot_lv = int(b.get("lv", 0))
                break

    mapping = {
        "food": 1002,
        "wood": 1003,
        "iron": 1004,
        "diamond": 1005,
    }

    result = {
        "unprotected": {},
        "safe": {},
        "depot": {},
        "total": {},
    }

    for name, resid in mapping.items():
        rid_str = str(resid)
        total_val = int(float(reslist.get(rid_str, 0) or 0))
        safe_val = int(float(saferes.get(rid_str, 0) or 0))
        depot_cap = get_depot_capacity(depot_lv, resid)

        unprot_val = max(0, total_val - safe_val - depot_cap)

        result["total"][name] = total_val
        result["safe"][name] = safe_val
        result["depot"][name] = depot_cap
        result["unprotected"][name] = unprot_val

    return result
